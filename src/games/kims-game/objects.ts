/**
 * The objects that can appear on a Kim's Game tray (question 017).
 *
 * Every emoji is a single code point from Unicode 13 or older: no ZWJ
 * sequences, no flags, no skin tones, and none that need the U+FE0F selector
 * to show as a picture, so they render the same on older Android phones.
 * The name is the cell's accessible label and the caption in the picker.
 */
